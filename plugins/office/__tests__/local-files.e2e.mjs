test('Electron 被终止后恢复未保存草稿，磁盘原文件保持上次保存版本', async ({ buddy }, info) => {
  let { instance, app, page, frame } = await setup(buddy)
  await create(frame, '文档')
  let body = frame.locator('.tiptap[contenteditable=true]').first()
  await expect(body).toBeVisible({ timeout: 60000 })
  await body.fill('last explicitly saved version')
  const original = info.outputPath('recoverable.docx')
  await chooseSave(app, original); await editorAction(frame, '另存为…')
  await expect(state(frame)).toHaveText('已保存')
  await body.fill('unsaved recovered after crash')
  await expect(state(frame)).toHaveText('未保存')
  await expect.poll(async () => {
    for await (const file of fs.glob(`**/extensions/data/${manifest.id}/documents/index.json`, { cwd: instance.home })) {
      const index = path.join(instance.home, file)
      const records = JSON.parse(await fs.readFile(index, 'utf8')).copies
      const draft = records.find(record => record.name === 'recoverable.docx')?.recovery
      if (draft) {
        const content = await docxText(path.join(path.dirname(index), 'files', draft.key))
        return content.includes('unsaved recovered after crash')
      }
    }
    return false
  }, { timeout: 15000 }).toBe(true)
  expect(await docxText(original)).not.toContain('unsaved recovered after crash')
  const child = app.process()
  const exited = new Promise(resolve => child.once('exit', resolve))
  expect(child.kill('SIGKILL')).toBe(true)
  await exited; await instance.stop()
  ;({ app, page } = await instance.launch())
  await expect(page.locator('.desktop-app-sidebar')).toBeVisible()
  await page.locator('.desktop-app-sidebar').getByRole('button', { name: 'Office', exact: true }).click()
  await expect.poll(async () => {
    frame = page.frames().find(item => item.url().startsWith('lexora-extension:'))
    return frame && await frame.getByRole('button', { name: '本地文件', exact: true }).isVisible().catch(() => false)
  }, { timeout: 60000 }).toBe(true)
  await frame.getByRole('button', { name: '本地文件', exact: true }).click()
  await expect(frame.locator('tr').filter({ hasText: 'recoverable.docx' })).toContainText('有恢复草稿')
  await frame.getByRole('button', { name: 'recoverable.docx', exact: true }).click()
  body = frame.locator('.tiptap[contenteditable=true]').first()
  await expect(body).toContainText('unsaved recovered after crash')
  await expect(state(frame)).toHaveText('未保存')
  expect(await docxText(original)).toContain('last explicitly saved version')
  await page.screenshot({ path: info.outputPath('recovered-draft.png') })
  await save(frame)
  expect(await docxText(original)).toContain('unsaved recovered after crash')
})
